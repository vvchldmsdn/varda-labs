// Specific phrases must win over generic count suffixes such as "{0}건".
const compiledPatterns = messagePatterns.toSorted(([left], [right]) =>
  right.replace(/\{\d+\}/g, "").length - left.replace(/\{\d+\}/g, "").length,
).map(([ko, en]) => ({
  pattern: new RegExp(`^${ko.split(/\{\d+\}/).map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join(/^\{0\}(건|좌|주|개)$/.test(ko) ? "([+−-]?\\d[\\d,.]*)" : "(.+?)")}$`),
  en,
}));

/** Translate only display copy explicitly passed by a service-owned UI leaf. */
export function translateHomeHistory(value: string): string {
  if (!/[가-힣]/.test(value)) return value;
  const clean = value.replace(/\s+/g, " ").trim();
  const exact = translationEntry(homeHistoryMessages, clean);
  if (exact !== undefined) return exact;
  for (const { pattern, en } of compiledPatterns) {
    const match = pattern.exec(clean);
    if (match) return en.replace(/\{(\d+)\}/g, (_, index: string) => match[Number(index) + 1] ?? "");
  }
  return value;
}
