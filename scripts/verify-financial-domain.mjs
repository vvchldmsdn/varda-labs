import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

export const financialFiles = Object.freeze([
  "portfolio-math.ts",
  "portfolio-movement.ts",
  "current-holding-movement.ts",
]);
const authority = "packages/cairn-financial-domain/src";
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
const readIfPresent = file => fs.existsSync(file) ? fs.readFileSync(file) : null;

/** Verify the emitted application files. Sync only files which still match the
 * previous emission (or already match the new canonical source). Preflight the
 * entire set before writing anything, so an edit is never silently discarded. */
export function verifyFinancialDomain(root, { sync = false } = {}) {
  const manifestFile = path.join(root, "src/lib/shared-financial-domain.manifest.json");
  const priorBytes = readIfPresent(manifestFile);
  const prior = priorBytes ? JSON.parse(priorBytes.toString("utf8")) : null;
  if (prior && (prior.version !== 1 || prior.authority !== authority ||
      Object.keys(prior.files ?? {}).sort().join("|") !== [...financialFiles].sort().join("|") ||
      financialFiles.some(file => !/^[a-f0-9]{64}$/.test(prior.files[file])))) {
    throw new Error("Invalid financial domain manifest; restore its last reviewed version before syncing.");
  }
  if (!sync && !prior) throw new Error("Financial domain manifest missing.");

  const manifest = { version: 1, authority, files: {} };
  const outputs = financialFiles.map(file => {
    const source = fs.readFileSync(path.join(root, authority, file));
    const sourceHash = hash(source);
    manifest.files[file] = sourceHash;
    const target = path.join(root, "src/lib", file);
    const currentBytes = readIfPresent(target);
    const currentHash = currentBytes ? hash(currentBytes) : null;
    if (sync) {
      // Initial registration requires any existing output to equal canonical.
      // Subsequent emissions may replace only the previous generated bytes.
      if (currentHash !== null && currentHash !== sourceHash &&
          (!prior || currentHash !== prior.files[file])) {
        throw new Error("Refusing to overwrite edited consumer src/lib/" + file + ". Reconcile its edits into canonical source first.");
      }
    } else if (sourceHash !== prior.files[file] || currentHash !== sourceHash) {
      throw new Error("Financial domain divergence: " + file + ". Review canonical edits, then run node scripts/verify-financial-domain.mjs --sync.");
    }
    return { target, source, changed: currentHash !== sourceHash };
  });

  if (sync) {
    for (const output of outputs) if (output.changed) {
      fs.mkdirSync(path.dirname(output.target), { recursive: true });
      fs.writeFileSync(output.target, output.source);
    }
    fs.mkdirSync(path.dirname(manifestFile), { recursive: true });
    fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + "\n");
  }
  return manifest;
}

const invoked = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invoked) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== "--sync")) throw new Error("Usage: node scripts/verify-financial-domain.mjs [--sync]");
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  verifyFinancialDomain(root, { sync: args.includes("--sync") });
  console.log("PASS: canonical financial calculations, generated consumers and manifest match.");
}
